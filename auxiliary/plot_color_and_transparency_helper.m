function [line_handle, fill_handle] = plot_color_and_transparency_helper( ...
    axes_handle, position_grid, probability_density, base_color, opacity, legend_name)
%PLOT_COLOR_AND_TRANSPARENCY_HELPER 色彩与透明度的作图辅助函数。
% opacity 表示不透明度：0 为完全透明，1 为完全不透明。

opacity = clamp_value_to_limits_helper(opacity, 0, 1);
base_color = clamp_value_to_limits_helper(base_color, 0, 1);

% R2019a 的普通折线不直接支持 alpha，因此将线色与白色背景混合。
visible_line_color = 1 - opacity * (1 - base_color);
zero_density = zeros(size(probability_density));

hold(axes_handle, 'on');
fill_handle = patch(axes_handle, ...
    [position_grid, fliplr(position_grid)], ...
    [zero_density, fliplr(probability_density)], ...
    base_color, ...
    'FaceAlpha', opacity, ...
    'EdgeColor', 'none', ...
    'HandleVisibility', 'off');

line_handle = plot(axes_handle, position_grid, probability_density, ...
    'Color', visible_line_color, ...
    'LineWidth', 2, ...
    'DisplayName', legend_name);
end
